#!/usr/bin/env python3
"""Freeze Unicode data and independent whole-string Python key/lower digests."""
import argparse
import _sre
import re
from re._casefix import _EXTRA_CASES
import ctypes
import hashlib
import json
import sys
import unicodedata
from pathlib import Path
from generate_rules import load, ranges


def main():
    if (sys.implementation.name != 'cpython' or sys.version_info[:3] != (3, 12, 15)
            or unicodedata.unidata_version != '15.0.0'):
        raise SystemExit('requires CPython3.12.15 / Unicode15.0.0')
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'src/unicode15.rs')
    parser.add_argument('--oracle-output', type=Path, default=Path(__file__).with_name('unicode15-oracle.json'))
    args = parser.parse_args()
    ef = load(args.source)
    scalars = [cp for cp in range(0x110000) if not 0xd800 <= cp <= 0xdfff]
    def rust(value):
        return '"' + ''.join('\\u{' + format(ord(c), 'x') + '}' for c in value) + '"'
    def prop(name):
        f = getattr(ctypes.pythonapi, name)
        f.argtypes = [ctypes.c_uint32]
        f.restype = ctypes.c_int
        return f
    ignorable = prop('_PyUnicode_IsCaseIgnorable')
    cased = prop('_PyUnicode_IsCased')
    assert all(bool(cased(cp)) == (chr(cp).isupper() or chr(cp).islower() or unicodedata.category(chr(cp)) == 'Lt') for cp in scalars)
    lines = ['// Generated by tests/generate_unicode15.py from CPython3.12.15 / Unicode15.0.0.',
             '// Runtime uses static data only; no host Unicode or Python/FFI.',
             'pub(super) const LOWER: &[(u32, &str)] = &[']
    for cp in scalars:
        c = chr(cp)
        if c.lower() != c:
            lines.append(f'    (0x{cp:x}, {rust(c.lower())}),')
    lines += ['];', 'pub(super) const NFKD: &[(u32, &str)] = &[']
    for cp in scalars:
        c = chr(cp)
        decomposed = unicodedata.normalize('NFKD', c)
        if decomposed != c:
            lines.append(f'    (0x{cp:x}, {rust(decomposed)}),')
    lines += ['];', 'pub(super) const IGNORABLE: &[(u32, u32)] = &[']
    ignore_ranges = ranges(lambda c: bool(ignorable(ord(c))))
    lines += [f'    (0x{a:x}, 0x{b:x}),' for a, b in ignore_ranges]
    lines.append('];')
    parents = {}
    def root(x):
        parents.setdefault(x, x)
        if parents[x] != x:
            parents[x] = root(parents[x])
        return parents[x]
    def union(a, b):
        a, b = root(a), root(b)
        if a != b:
            parents[max(a, b)] = min(a, b)
    for cp in scalars:
        lower = _sre.unicode_tolower(cp)
        if lower != cp:
            union(cp, lower)
    for a, others in _EXTRA_CASES.items():
        for b in others:
            union(a, b)
    groups = {}
    for cp in list(parents):
        groups.setdefault(root(cp), []).append(cp)
    classes = {}
    for members in groups.values():
        members.sort()
        for cp in members:
            classes[cp] = members
    lines.append('pub(super) const RE_CASES: &[(u32, &[u32])] = &[')
    regex_pairs = []
    for cp, members in sorted(classes.items()):
        lines.append(f'    (0x{cp:x}, &[{", ".join(f"0x{x:x}" for x in members)}]),')
        pattern = re.compile(re.escape(chr(cp)), re.I)
        assert all(pattern.fullmatch(chr(other)) for other in members)
        for other in sorted(set(members + [max(0, cp-1), min(0x10ffff, cp+1), 0x41, 0x345, 0x1c89])):
            regex_pairs.append((cp, other, bool(pattern.fullmatch(chr(other)))))
    lines.append('];')
    def digest(pairs):
        h = hashlib.sha256()
        for cp, value in pairs:
            data = value.encode('utf-8')
            h.update(cp.to_bytes(4, 'big'))
            h.update(len(data).to_bytes(4, 'big'))
            h.update(data)
        return h.hexdigest()
    points = {0, 0x10ffff, 0x345, 0x1c89, 0x1c8a, 0x1ccd6}
    for f in [cased, ignorable]:
        for a, b in ranges(lambda c: bool(f(ord(c)))):
            for cp in [a-1, a, b, b+1]:
                if 0 <= cp <= 0x10ffff and not 0xd800 <= cp <= 0xdfff:
                    points.add(cp)
    contexts = []
    for cp in sorted(points):
        c = chr(cp)
        contexts.extend(['AΣ'+c, 'AΣ'+c+'A', c+'Σ', c+'ΣA', 'A'+c+'Σ'])
    contexts += ['A\u0345Σ\u0301B', 'AΣ\u0345', 'ﬃ\u0301Σ', 'ᾈΣ', 'A\u0345\u034fΣ\u034fB']
    property_patterns = [re.compile(pattern, re.I) for pattern in [r'\s', r'\d', r'[^\W\d_]', r'\w']]
    property_hash = hashlib.sha256()
    for cp in scalars:
        bits = sum(bool(pattern.fullmatch(chr(cp))) << i for i, pattern in enumerate(property_patterns))
        property_hash.update(cp.to_bytes(4, 'big'))
        property_hash.update(bytes([bits]))
    oracle = {'regex_properties_sha256': property_hash.hexdigest(), 'python': sys.version.split()[0], 'unicode': unicodedata.unidata_version,
              'source_sha256': hashlib.sha256(args.source.read_bytes()).hexdigest(),
              'scalar_count': len(scalars),
              'scalar_lower_sha256': digest((cp, chr(cp).lower()) for cp in scalars),
              'scalar_key_sha256': digest((cp, ef._key(chr(cp))) for cp in scalars),
              'context_points': sorted(points), 'regex_pairs': regex_pairs,
              'context_lower_sha256': digest((i, s.lower()) for i, s in enumerate(contexts)),
              'context_key_sha256': digest((i, ef._key(s)) for i, s in enumerate(contexts))}
    args.output.write_text('\n'.join(lines)+'\n')
    args.oracle_output.write_text(json.dumps(oracle, separators=(',', ':'))+'\n')
    print(f'generated {len(scalars)} scalar proofs and {len(contexts)} whole-string contexts')


if __name__ == '__main__':
    main()
