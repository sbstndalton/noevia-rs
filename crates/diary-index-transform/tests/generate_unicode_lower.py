#!/usr/bin/env python3
"""Freeze shipped CPython lower mappings and Final_Sigma properties.

Only the generator calls CPython's property API. Production Rust uses static
Unicode 15 tables, no Python, FFI, host Unicode version or runtime IO.
"""
import ctypes
from pathlib import Path
import sys
import unicodedata

if sys.version_info[:3] != (3, 12, 15) or unicodedata.unidata_version != '15.0.0':
    raise SystemExit('requires shipped CPython 3.12.15 / Unicode 15.0.0')


def property_function(name):
    function = getattr(ctypes.pythonapi, name)
    function.argtypes = [ctypes.c_uint32]
    function.restype = ctypes.c_int
    return function


def scalar_values():
    return (cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF)


def rust_string(value):
    return '"' + ''.join('\\u{' + format(ord(c), 'x') + '}' for c in value) + '"'


def ranges(property_fn):
    result = []
    for cp in scalar_values():
        if property_fn(cp):
            if result and result[-1][1] + 1 == cp:
                result[-1][1] = cp
            else:
                result.append([cp, cp])
    return result


lines = [
    '// Generated by tests/generate_unicode_lower.py; do not edit by hand.',
    '// CPython 3.12.15 / Unicode 15.0.0; full lower plus Final_Sigma properties.',
    'pub(super) const LOWER: &[(u32, &str)] = &[',
]
for cp in scalar_values():
    c = chr(cp)
    if c.lower() != c:
        lines.append(f'    (0x{cp:x}, {rust_string(c.lower())}),')
lines.append('];')
for name, api in [('CASED', '_PyUnicode_IsCased'), ('IGNORABLE', '_PyUnicode_IsCaseIgnorable')]:
    lines.append(f'pub(super) const {name}: &[(u32, u32)] = &[')
    for start, end in ranges(property_function(api)):
        lines.append(f'    (0x{start:x}, 0x{end:x}),')
    lines.append('];')
Path(__file__).resolve().parents[1].joinpath('src/unicode15.rs').write_text('\n'.join(lines) + '\n')

# Independent whole-string Python results exercise each context property
# boundary and lowercase mapping, including characters unknown to Unicode 15.
points = {0, 0x10FFFF, 0x10D50, 0x10D70, 0x1C89, 0x1C8A, 0x345}
for api in ['_PyUnicode_IsCased', '_PyUnicode_IsCaseIgnorable']:
    for start, end in ranges(property_function(api)):
        for cp in [start - 1, start, end, end + 1]:
            if 0 <= cp <= 0x10FFFF and not 0xD800 <= cp <= 0xDFFF:
                points.add(cp)
lines = ['// Generated CPython 3.12.15 whole-string lower oracle.', 'pub const CONTEXTS: &[(&str, &str)] = &[']
for cp in sorted(points):
    for text in ['AΣ' + chr(cp), 'AΣ' + chr(cp) + 'A', chr(cp) + 'Σ', chr(cp) + 'ΣA', 'A' + chr(cp) + 'Σ']:
        lines.append(f'    ({rust_string(text)}, {rust_string(text.lower())}),')
lines.append('];')
Path(__file__).with_name('oracles').joinpath('unicode_contexts.rs').write_text('\n'.join(lines) + '\n')
