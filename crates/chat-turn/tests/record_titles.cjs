function ranges(re) {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp += 1) {
    const hit = cp <= 0x10ffff && cp !== undefined && !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
    if (hit && start < 0) start = cp;
    if (!hit && start >= 0) { out.push([start, cp - 1]); start = -1; }
  }
  return out;
}
