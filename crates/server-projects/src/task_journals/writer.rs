//! Native append/recovery primitive. Call from blocking task work only. The task runtime must
//! acquire sole ownership from the legacy writer before opening this store.
use super::{
    bound_code_plan, bound_review, clip_utf8, derive, parse_rows, valid_id, Job, Parsed, Surface,
    MAX_JOURNAL_BYTES,
};
use crate::store;
use js_json::{wtf16, JValue};
use sha2::{Digest, Sha256};
use std::{
    fs,
    io::{Read, Seek, SeekFrom, Write},
    path::{Path, PathBuf},
};

#[derive(Debug)]
pub enum Error {
    InvalidId,
    Missing,
    Finished,
    Unreadable,
    WrongSurface,
    InvalidEvent,
    Busy,
    Io(std::io::Error),
}
impl From<std::io::Error> for Error {
    fn from(e: std::io::Error) -> Self {
        Self::Io(e)
    }
}

/// Synchronous journal transactions use one directory lock; no async work runs under it.
struct Held(fs::File);
impl Drop for Held {
    fn drop(&mut self) {
        let _ = self.0.unlock();
    }
}

pub struct Store {
    root: PathBuf,
    surface: Surface,
}
impl Store {
    pub fn open(data_dir: &Path, user: &str, surface: Surface) -> Result<Self, Error> {
        let root = store::user_dir(data_dir, user)
            .map_err(|_| Error::InvalidId)?
            .join("jobs");
        let user_dir = root.parent().ok_or(Error::InvalidId)?;
        for dir in [data_dir.join("users"), user_dir.to_path_buf()] {
            if !fs::symlink_metadata(dir)?.file_type().is_dir() {
                return Err(Error::Unreadable);
            }
        }
        match fs::create_dir(&root) {
            Ok(()) => {
                #[cfg(unix)]
                {
                    use std::os::unix::fs::PermissionsExt;
                    fs::set_permissions(&root, fs::Permissions::from_mode(0o700))?;
                }
            }
            Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {}
            Err(e) => return Err(e.into()),
        }
        if !fs::symlink_metadata(&root)?.is_dir() {
            return Err(Error::Unreadable);
        }
        Ok(Self { root, surface })
    }
    fn hold(&self) -> Result<Held, Error> {
        if !fs::symlink_metadata(&self.root)?.file_type().is_dir() {
            return Err(Error::Unreadable);
        }
        let mut options = fs::OpenOptions::new();
        options.read(true).write(true).create(true).truncate(false);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            options
                .mode(0o600)
                .custom_flags(libc::O_NOFOLLOW | libc::O_NONBLOCK);
        }
        let file = options.open(self.root.join("native-task-writer.lock"))?;
        if !file.metadata()?.is_file() {
            return Err(Error::Unreadable);
        }
        file.try_lock().map_err(|e| match e {
            fs::TryLockError::WouldBlock => Error::Busy,
            fs::TryLockError::Error(e) => Error::Io(e),
        })?;
        Ok(Held(file))
    }
    fn path(&self, id: &str) -> Result<PathBuf, Error> {
        if !valid_id(id) {
            return Err(Error::InvalidId);
        }
        Ok(self.root.join(format!("{id}.jsonl")))
    }
    /// The id is generated by the actor; create_new prevents clobbering an existing job.
    pub fn create(
        &self,
        id: &str,
        project: &str,
        capabilities: Vec<JValue>,
        now: i64,
    ) -> Result<Job, Error> {
        let _held = self.hold()?;
        let path = self.path(id)?;
        self.prune_locked(now)?;
        let mut options = fs::OpenOptions::new();
        options.write(true).create_new(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            options.mode(0o600).custom_flags(libc::O_NOFOLLOW);
        }
        let mut file = options.open(path)?;
        let data = object(vec![
            ("kind", JValue::Str(self.surface.kind().into())),
            ("projectId", JValue::Str(project.into())),
            ("parentId", JValue::Null),
            ("capabilities", JValue::Arr(capabilities)),
        ]);
        let event = event(id, 1, "job.created", data, now);
        write_event(&mut file, &event, false)?;
        Ok(derive(&[event]))
    }
    /// Only ordinary executor events are accepted. Planner authority needs its own validated API.
    pub fn append(&self, id: &str, kind: &str, data: JValue, now: i64) -> Result<Job, Error> {
        if !matches!(
            kind,
            "job.started"
                | "progress"
                | "step.started"
                | "step.completed"
                | "approval.requested"
                | "approval.decided"
                | "tool.started"
                | "tool.completed"
                | "tool.uncertain"
                | "artifact.created"
                | "checkpoint.created"
                | "job.completed"
                | "job.failed"
                | "job.cancelled"
                | "job.interrupted"
                | "plan.proposed"
                | "plan.edited"
                | "plan.skipped"
                | "assistant.output"
                | "review.requested"
                | "review.completed"
                | "review.failed"
        ) {
            return Err(Error::InvalidEvent);
        }
        let _held = self.hold()?;
        self.append_locked(id, kind, data, now)
    }
    fn append_locked(&self, id: &str, kind: &str, data: JValue, now: i64) -> Result<Job, Error> {
        let mut file = self.open_file(id)?;
        let (mut rows, end) = read(&mut file, id)?;
        if rows.is_empty() {
            return Err(Error::Missing);
        }
        let job = derive(&rows);
        if job.kind.as_str() != Some(self.surface.kind()) {
            return Err(Error::WrongSurface);
        }
        if terminal(&job)
            && !(kind == "artifact.created" && job.status.as_str() == Some("cancelled"))
        {
            return Err(Error::Finished);
        }
        let data = bound_data(&rows, self.surface, kind, data)?;
        let mut next = event(id, rows.len() + 1, kind, data, now);
        let durable = rows.first().is_some_and(|r| r.get("hash").truthy());
        if durable {
            let JValue::Obj(fields) = &mut next else {
                return Err(Error::Unreadable);
            };
            fields.push((
                "previous".into(),
                rows.last()
                    .map(|r| r.get("hash").clone())
                    .unwrap_or(JValue::Null),
            ));
            let encoded = wtf16::stringify(&next).ok_or(Error::Unreadable)?;
            let digest = Sha256::digest(encoded.as_bytes())
                .iter()
                .map(|b| format!("{b:02x}"))
                .collect::<String>();
            if let JValue::Obj(fields) = &mut next {
                fields.push(("hash".into(), JValue::Str(digest)));
            }
        }
        file.set_len(end)?;
        file.seek(SeekFrom::Start(end))?;
        write_event(&mut file, &next, durable)?;
        if durable {
            fs::File::open(&self.root)?.sync_all()?;
        }
        rows.push(next);
        Ok(derive(&rows))
    }
    fn open_file(&self, id: &str) -> Result<fs::File, Error> {
        let mut options = fs::OpenOptions::new();
        options.read(true).write(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            options.custom_flags(libc::O_NOFOLLOW | libc::O_NONBLOCK);
        }
        let file = options.open(self.path(id)?)?;
        if !file.metadata()?.is_file() {
            return Err(Error::Unreadable);
        }
        Ok(file)
    }
    fn prune_locked(&self, now: i64) -> Result<(), Error> {
        let retain = match self.surface {
            Surface::Code => 14.0,
            Surface::Browser => 7.0,
        } * 86_400_000.0;
        let mut done = Vec::new();
        for entry in fs::read_dir(&self.root)? {
            let entry = entry?;
            let name = entry.file_name();
            let Some(id) = name
                .to_str()
                .and_then(|s| s.strip_suffix(".jsonl"))
                .filter(|id| valid_id(id))
            else {
                continue;
            };
            let Ok(mut file) = self.open_file(id) else {
                continue;
            };
            let Ok((rows, _)) = read(&mut file, id) else {
                continue;
            };
            if rows.is_empty() {
                continue;
            }
            let job = derive(&rows);
            if job.kind.as_str() != Some(self.surface.kind()) || !terminal(&job) {
                continue;
            }
            // An unknown clock is not a reason to delete uncertain legacy state.
            if let Some(at) = job.updated_at.as_num().filter(|n| n.is_finite()) {
                done.push((id.to_owned(), at));
            }
        }
        done.sort_by(|a, b| b.1.total_cmp(&a.1));
        for (index, (id, at)) in done.into_iter().enumerate() {
            if now as f64 - at > retain || index >= 50 {
                fs::remove_file(self.path(&id)?)?;
            }
        }
        Ok(())
    }
    /// Explicit durable receipt for a cleanup report before acknowledging native retention.
    /// Ordinary plain journals otherwise follow Node's write-only policy; inherited chains sync.
    pub fn sync(&self, id: &str) -> Result<(), Error> {
        let _held = self.hold()?;
        let mut file = self.open_file(id)?;
        let (rows, _) = read(&mut file, id)?;
        let job = derive(&rows);
        if rows.is_empty() {
            return Err(Error::Missing);
        }
        if job.kind.as_str() != Some(self.surface.kind()) {
            return Err(Error::WrongSurface);
        }
        file.sync_all()?;
        fs::File::open(&self.root)?.sync_all()?;
        Ok(())
    }
    /// Once per actor incarnation, before any new task is admitted. Never resumes approvals.
    pub fn recover(&self, now: i64) -> Result<usize, Error> {
        let _held = self.hold()?;
        let mut count = 0;
        for entry in fs::read_dir(&self.root)? {
            let entry = entry?;
            let name = entry.file_name();
            let Some(id) = name
                .to_str()
                .and_then(|n| n.strip_suffix(".jsonl"))
                .filter(|id| valid_id(id))
            else {
                continue;
            };
            let Ok(mut file) = self.open_file(id) else {
                continue;
            };
            let Ok((rows, _)) = read(&mut file, id) else {
                continue;
            };
            if rows.is_empty() {
                continue;
            }
            let job = derive(&rows);
            if job.kind.as_str() != Some(self.surface.kind()) || terminal(&job) {
                continue;
            }
            let reason = if job.status.as_str() == Some("waiting_approval") {
                "The server restarted while waiting for approval; start again to be asked again."
            } else {
                "The server restarted before this finished."
            };
            self.append_locked(
                id,
                "job.interrupted",
                object(vec![("reason", JValue::Str(reason.into()))]),
                now,
            )?;
            count += 1;
        }
        Ok(count)
    }
}
fn terminal(job: &Job) -> bool {
    matches!(
        job.status.as_str(),
        Some("completed" | "failed" | "cancelled" | "interrupted")
    )
}
fn object(fields: Vec<(&str, JValue)>) -> JValue {
    JValue::Obj(fields.into_iter().map(|(k, v)| (k.into(), v)).collect())
}
fn event(id: &str, seq: usize, kind: &str, data: JValue, now: i64) -> JValue {
    object(vec![
        ("job", JValue::Str(id.into())),
        ("seq", JValue::Num(seq as f64)),
        ("type", JValue::Str(kind.into())),
        ("at", JValue::Num(now as f64)),
        ("data", data),
    ])
}
fn read(file: &mut fs::File, id: &str) -> Result<(Vec<JValue>, u64), Error> {
    if file.metadata()?.len() > MAX_JOURNAL_BYTES {
        return Err(Error::Unreadable);
    }
    let mut bytes = Vec::new();
    file.take(MAX_JOURNAL_BYTES + 1).read_to_end(&mut bytes)?;
    if bytes.len() as u64 > MAX_JOURNAL_BYTES {
        return Err(Error::Unreadable);
    }
    let end = bytes.iter().rposition(|b| *b == b'\n').map_or(0, |i| i + 1);
    let Parsed::Rows(rows) = parse_rows(id, &bytes) else {
        return Err(Error::Unreadable);
    };
    if end != bytes.len() && rows.first().is_some_and(|r| r.get("hash").truthy()) {
        return Err(Error::Unreadable);
    }
    // Node checks state and computes the next sequence from every valid parsed row, even a
    // complete final JSON value with no newline. Only the physical append truncates that tail.
    // In particular a terminal tail must never be discarded before the finished-state check.
    Ok((rows, end as u64))
}
fn write_event(file: &mut fs::File, event: &JValue, durable: bool) -> Result<(), Error> {
    let mut encoded = wtf16::stringify(event).ok_or(Error::Unreadable)?;
    encoded.push('\n');
    if file.metadata()?.len().saturating_add(encoded.len() as u64) > MAX_JOURNAL_BYTES {
        return Err(Error::Unreadable);
    }
    file.write_all(encoded.as_bytes())?;
    if durable {
        file.sync_all()?;
    }
    Ok(())
}

fn bound_data(
    rows: &[JValue],
    surface: Surface,
    kind: &str,
    data: JValue,
) -> Result<JValue, Error> {
    if kind == "assistant.output" {
        if surface != Surface::Code {
            return Err(Error::WrongSurface);
        }
        if rows
            .iter()
            .filter(|row| row.get("type").as_str() == Some(kind))
            .count()
            >= 64
        {
            return Err(Error::InvalidEvent);
        }
        let incoming = data.get("text").as_str().unwrap_or("");
        let (text, cut) = clip_utf8(incoming, 1024);
        return Ok(object(vec![
            ("text", JValue::Str(text)),
            (
                "truncated",
                JValue::Bool(data.get("truncated") == &JValue::Bool(true) || cut),
            ),
        ]));
    }
    if matches!(kind, "plan.proposed" | "plan.edited" | "plan.skipped") {
        if surface != Surface::Code {
            return Err(Error::WrongSurface);
        }
        let empty = JValue::Null;
        let data = if kind == "plan.skipped" {
            &empty
        } else {
            &data
        };
        if let JValue::Arr(entries) = data.get("subQuestions") {
            for entry in entries.iter().take(20).filter(|e| !e.is_nullish()) {
                js_json::to_js_string(entry).map_err(|_| Error::InvalidEvent)?;
            }
        }
        let mut bounded = bound_code_plan("", data);
        if let JValue::Obj(fields) = &mut bounded {
            fields.retain(|(key, _)| key != "status");
        }
        return Ok(bounded);
    }
    if matches!(
        kind,
        "review.requested" | "review.completed" | "review.failed"
    ) {
        if surface != Surface::Code {
            return Err(Error::WrongSurface);
        }
        return Ok(bound_review(kind, &data));
    }
    Ok(data)
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod lock_tests {
    use super::*;
    #[test]
    fn transaction_drop_unlocks_even_while_a_duplicate_descriptor_survives() {
        let root = tempfile::tempdir().unwrap();
        let path = root.path().join("lock");
        let file = fs::OpenOptions::new()
            .read(true)
            .write(true)
            .create_new(true)
            .open(&path)
            .unwrap();
        file.try_lock().unwrap();
        let held = Held(file);
        let duplicate = held.0.try_clone().unwrap();
        drop(held);
        let successor = fs::OpenOptions::new()
            .read(true)
            .write(true)
            .open(path)
            .unwrap();
        successor.try_lock().unwrap();
        drop(duplicate);
    }
}
