"""Regenerate `src/unicode15.rs` (Unicode 15.0.0 data used by the follow-up resolver).

Usage (stdlib only, isolated mode):

    python3.12 -I crates/diary-core/tests/generate_unicode15.py

Refuses to run unless the interpreter is CPython 3.12 with `unicodedata.unidata_version == "15.0.0"`,
the data the production Python service (python:3.12) and the diary-entity-focus crate are pinned to.
Two tables are written:

- OTHER: inclusive code point ranges whose general category starts with "C" (Cc, Cf, Cs, Co and the
  unassigned Cn), what `safe_name` replaces with a space.
- CASEFOLD: every code point whose `str.casefold()` differs from itself, with the full folding, what
  `mentions` compares. CPython folds each code point on its own (no context rules), so a per-code-point
  table is exact.
"""

import pathlib
import sys
import unicodedata

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "unicode15.rs"


def main():
    if sys.version_info[:2] != (3, 12) or unicodedata.unidata_version != "15.0.0":
        sys.exit(
            f"refusing: need CPython 3.12 / Unicode 15.0.0, got {sys.version.split()[0]} / "
            f"{unicodedata.unidata_version}"
        )
    ranges = []
    for cp in range(0x110000):
        if unicodedata.category(chr(cp))[0] == "C":
            if ranges and ranges[-1][1] == cp - 1:
                ranges[-1][1] = cp
            else:
                ranges.append([cp, cp])
    fold = []
    for cp in range(0x110000):
        c = chr(cp)
        folded = c.casefold()
        if folded != c:
            fold.append((cp, folded))
    lines = [
        f"// Generated by tests/generate_unicode15.py from CPython {sys.version.split()[0]} / "
        f"Unicode {unicodedata.unidata_version}.",
        "// Runtime uses these static tables only; no host Unicode data and no Python.",
        "",
        "/// Inclusive code point ranges of general category C* (Cc, Cf, Cs, Co, Cn).",
        "pub(crate) const OTHER: &[(u32, u32)] = &[",
    ]
    lines += [f"    (0x{a:x}, 0x{b:x})," for a, b in ranges]
    lines += [
        "];",
        "",
        "/// Full case folding (`str.casefold`) of every code point it changes.",
        "pub(crate) const CASEFOLD: &[(u32, &str)] = &[",
    ]
    for cp, folded in fold:
        escaped = "".join(f"\\u{{{ord(c):x}}}" for c in folded)
        lines.append(f'    (0x{cp:x}, "{escaped}"),')
    lines += ["];", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(ranges)} ranges, {len(fold)} folds)")


if __name__ == "__main__":
    main()
