#!/usr/bin/env node
'use strict';
// Prints crates/project-file-names/src/nfc_pairs.rs (noevia#1211): every pair of an NFC-inert base
// U+0000-U+02FF and one combining mark U+0300-U+036F whose NFC form is a single code point that is
// itself in U+0000-U+02FF (so NFC-inert), from this runtime's own normalize(). These canonical
// compositions are fixed by Unicode's normalization stability policy; noevia-core's
// project-file-names differential test checks the shipped module against the runtime for every pair.
//   node tools/gen-nfc-pairs.cjs > crates/project-file-names/src/nfc_pairs.rs
const pairs = [];
for (let base = 0; base < 0x300; base++) {
  for (let mark = 0x300; mark < 0x370; mark++) {
    const nfc = [...String.fromCharCode(base, mark).normalize('NFC')];
    if (nfc.length !== 1) continue;
    const cp = nfc[0].codePointAt(0);
    if (cp < 0x300) pairs.push([base, mark, cp]);
  }
}
const hex = (n) => `0x${n.toString(16).padStart(4, '0')}`;
const lines = pairs.map(([b, m, c]) => `    (${hex(b)}, ${hex(m)}, ${hex(c)}),`);
process.stdout.write(`// @generated by tools/gen-nfc-pairs.cjs (Unicode ${process.versions.unicode}); do not edit.

/// \`(base, mark, NFC(base + mark))\`, sorted by base then mark: an NFC-inert base U+0000-U+02FF and
/// one combining mark U+0300-U+036F that compose to one code point in U+0000-U+02FF.
pub const NFC_PAIRS: [(u16, u16, u16); ${pairs.length}] = [
${lines.join('\n')}
];
`);
