#!/usr/bin/env python3
"""Generate Rust static specs and the Node mirror from the canonical Rust contract."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "contracts/features/catalog.json"
RUST = ROOT / "crates/server-features/src/catalog_generated.rs"
KIND = {
    "none": "Static",
    "decisionChoice": "DecisionChoice",
    "systemOne": "SystemOne",
    "browser": "Browser",
    "codeSandbox": "CodeSandbox",
    "trustProxy": "TrustProxy",
}


def lit(value):
    return json.dumps(value, ensure_ascii=False)


def variant(name):
    return name[0].upper() + name[1:]


def rust_source(features):
    lines = [
        "// Generated by tools/features/generate_catalog.py from contracts/features/catalog.json.",
        "// Edit the JSON contract, then regenerate; the CI check rejects a stale generated file.",
        "#[derive(Clone, Copy, Debug, Eq, PartialEq)]",
        "pub enum Feature {",
    ]
    lines.extend(f"    {variant(row['id'])}," for row in features)
    lines.extend(["}", "", "impl Feature {", f"    pub const ALL: [Self; {len(features)}] = ["])
    lines.extend(f"        Self::{variant(row['id'])}," for row in features)
    lines.extend(["    ];", "", "    pub fn from_name(name: &str) -> Option<Self> {", "        match name {"])
    lines.extend(f"            {lit(row['id'])} => Some(Self::{variant(row['id'])})," for row in features)
    lines.extend(["            _ => None,", "        }", "    }", "",
                  "    pub fn from_input_name(name: &str) -> Option<Self> {",
                  "        match name {"])
    for row in features:
        if row["legacy"] is not None:
            lines.append(f"            {lit(row['legacy'])} => Some(Self::{variant(row['id'])}),")
    lines.extend(["            _ => Self::from_name(name),", "        }", "    }", "}", "",
                  "pub const fn spec(feature: Feature) -> Spec {", "    match feature {"])
    for row in features:
        lines.extend([
            f"        Feature::{variant(row['id'])} => Spec {{",
            f"            name: {lit(row['id'])},",
            f"            env: {lit(row['env'])},",
            f"            setting: {lit('feature:' + row['id'])},",
            f"            default: {str(row['default']).lower()},",
            f"            experimental: {str(row['experimental']).lower()},",
            f"            restart: {str(row['restart']).lower()},",
            f"            legacy: {'Some(' + lit(row['legacy']) + ')' if row['legacy'] else 'None'},",
            f"            label: {lit(row['label'])},",
            f"            description: {lit(row['description'])},",
            f"            availability: AvailabilityKind::{KIND[row['availability']]},",
            "        },",
        ])
    lines.extend(["    }", "}", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--core-output", type=Path)
    args = parser.parse_args()
    source = CATALOG.read_bytes()
    catalog = json.loads(source)
    if catalog["version"] != 1 or len(catalog["features"]) != 23:
        raise SystemExit("unsupported feature catalog version or cardinality")
    features = catalog["features"]
    names = [row["id"] for row in features]
    if len(names) != len(set(names)) or any(row["availability"] not in KIND for row in features):
        raise SystemExit("invalid feature catalog")
    rust = rust_source(features).encode()
    outputs = [(RUST, rust)]
    if args.core_output:
        outputs.append((args.core_output, source))
    if args.check:
        stale = [str(path) for path, data in outputs if not path.exists() or path.read_bytes() != data]
        if stale:
            raise SystemExit("generated feature catalog mismatch: " + ", ".join(stale))
    else:
        for path, data in outputs:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)


if __name__ == "__main__":
    main()
